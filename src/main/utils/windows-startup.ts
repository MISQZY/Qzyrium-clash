import { app } from 'electron'
import { execFile } from 'node:child_process'
import path from 'node:path'
import type { AppConfig } from '@shared/app-config'
import { logger } from './logger'

// Old releases passed encoded PowerShell commands directly to the process;
// they did not install .ps1 files. Only their per-user startup tasks persist.
export async function removeLegacyStartupTasks(): Promise<void> {
  if (process.platform !== 'win32') return
  const schtasks = process.env.SystemRoot
    ? path.join(process.env.SystemRoot, 'System32', 'schtasks.exe')
    : 'schtasks.exe'
  const options = { windowsHide: true, timeout: 5000, maxBuffer: 4 * 1024 * 1024 }
  const run = (args: string[]): Promise<string> => new Promise((resolve, reject) => {
    execFile(schtasks, args, options, (error, stdout) => error ? reject(error) : resolve(stdout))
  })
  try {
    const stdout = await run(['/query', '/fo', 'csv', '/nh'])
    for (const line of stdout.split(/\r?\n/)) {
      // Match only root tasks generated by the old SID-based naming scheme.
      const match = line.match(/^"(\\?Qzyrium-clash-Startup-S-\d+(?:-\d+)+)"/i)
      if (!match) continue
      const taskName = match[1]
      try {
        await run(['/delete', '/tn', taskName, '/f'])
        logger.info(`Removed legacy scheduled task: ${taskName}`)
      } catch (err) {
        // Keep retrying on subsequent launches, including an elevated restart.
        logger.warn(`Could not remove legacy startup task ${taskName}: ${String(err)}`)
      }
    }
  } catch (err) {
    logger.warn(`Could not query legacy startup tasks: ${String(err)}`)
  }
}

// The existing runner handles elevation on launch. Native login registration
// replaces both legacy startup modes without invoking PowerShell or prompting UAC.
export async function applyWindowsStartup(general: AppConfig['general']): Promise<void> {
  if (process.platform !== 'win32') return
  app.setLoginItemSettings({ openAtLogin: general.autoStart })
  await removeLegacyStartupTasks()
}
