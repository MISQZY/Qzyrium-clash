const assert = require('node:assert/strict')
const { loadTypeScript } = require('./fixtures/typescript.cjs')
const { LogBuffer } = loadTypeScript('src/shared/log-buffer.ts')
const { LogBatcher } = loadTypeScript('src/main/utils/log-batcher.ts')
const record = (id, source = 'app') => ({ time: '2026-01-01T00:00:00Z', payload: String(id), source, type: 'info' })
;(async () => {
  const buffer = new LogBuffer(3)
  for (let n = 0; n < 20; n++) buffer.push(record(n, n % 2 ? 'app' : 'mihomo'))
  assert.deepEqual(buffer.snapshot().map(x => x.payload), ['14', '15', '16', '17', '18', '19'])
  buffer.resize(2)
  assert.deepEqual(buffer.snapshot().map(x => x.payload), ['16', '17', '18', '19'])
  buffer.clear('app')
  assert.deepEqual(buffer.snapshot().map(x => x.payload), ['16', '18'])
  buffer.push(record('new'))
  assert.equal(buffer.snapshot().at(-1).payload, 'new')
  const batches = []
  const batcher = new LogBatcher(batch => batches.push(batch))
  for (let n = 0; n < 20000; n++) batcher.push(record(n))
  assert.equal(batches.length, 0, 'bursts do not send one IPC message per line')
  await new Promise(resolve => setTimeout(resolve, 150))
  assert.equal(batches.length, 1)
  assert.equal(batches[0].length, 500, 'queue is bounded per source')
  assert.equal(batches[0][0].payload, '19500')
  assert.equal(batches[0].at(-1).payload, '19999')
  batcher.push(record('old window'))
  batcher.clear()
  await new Promise(resolve => setTimeout(resolve, 150))
  assert.equal(batches.length, 1, 'disposed windows leave no delayed deliveries')
  batcher.push({ ...record('oversized'), payload: 'x'.repeat(3 * 1024 * 1024) })
  batcher.flush()
  assert.equal(batches.length, 1, 'oversized IPC records cannot grow the queue')
  batcher.push(record('next window'))
  batcher.flush()
  assert.equal(batches.at(-1)[0].payload, 'next window')
  console.log('PASS: per-source ring history, resizing, chronological batches, bounded bursts and lifecycle cancellation')
})().catch(error => { console.error(error); process.exitCode = 1 })
