const { app, BrowserWindow, contextBridge } = require('electron')
const path = require('node:path')
const fs = require('node:fs')

if (process.type === 'renderer') {
  const expose = contextBridge.exposeInMainWorld.bind(contextBridge)
  contextBridge.exposeInMainWorld = (name, api) => {
    let calls = [], selections = 0, release
    const selectProxy = api.mihomo.selectProxy
    api.mihomo.selectProxy = async (...args) => { selections++; return selectProxy(...args) }
    api.mihomo.checkServices = async host => {
      calls.push(host)
      return new Promise((resolve, reject) => { release = async status => {
        if (status === 'error') return reject(new Error('core unavailable'))
        const settings = await api.settings.get()
        resolve(settings.general.serviceCheckTargets.map(target => ({ id: target.id, status, delay: 42, region: target.kind === 'regional' ? 'NL' : undefined })))
      } })
    }
    expose('serviceTest', { calls: () => calls, selections: () => selections, finish: status => release(status) })
    expose(name, api)
  }
  require('./verify-ui.cjs')
} else {
  for (const [name, value] of require('./fixtures/rendering.cjs').renderingSwitches(process.platform)) app.commandLine.appendSwitch(name, value)
  const assert = require('node:assert/strict')
  const output = path.resolve(__dirname, '../artifacts/service-checks-ui-check')
  fs.mkdirSync(output, { recursive: true })
  app.setPath('userData', path.join(output, 'user-data'))
  app.whenReady().then(async () => {
    const win = new BrowserWindow({ show: false, width: 840, height: 720,
      webPreferences: { preload: __filename, sandbox: false, contextIsolation: true, backgroundThrottling: false } })
    const errors = []
    win.webContents.on('console-message', event => { if (event.level === 'error' || event.level >= 3) errors.push(event.message) })
    const evaluate = code => win.webContents.executeJavaScript(code)
    const waitFor = async code => {
      for (let i = 0; i < 100; i++) {
        if (await evaluate(`Boolean(${code})`)) return
        await new Promise(resolve => setTimeout(resolve, 50))
      }
      throw new Error(`Timed out: ${code}`)
    }
    const button = text => `Array.from(document.querySelectorAll('button')).find(el => el.textContent.trim() === ${JSON.stringify(text)})`
    const setInput = (label, value) => evaluate(`(() => { const input = document.querySelector('[aria-label="${label}"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, ${JSON.stringify(value)}); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
    try {
      await win.webContents.session.clearStorageData()
      await win.loadFile(path.resolve(__dirname, '../out/renderer/index.html'))
      await waitFor(`document.querySelector('[aria-label="Settings"]')`)
      await evaluate(`document.querySelector('[aria-label="Settings"]').click()`)
      await waitFor(`document.querySelector('[data-service-settings-list]')`)
      assert.equal(await evaluate(`document.querySelector('[data-service-settings-list]').closest('details').open`), false, 'service settings are collapsed by default')
      await evaluate(`document.querySelector('[data-service-settings-list]').closest('details').querySelector('summary').click()`)
      await waitFor(`document.querySelector('[data-service-settings-list]').closest('details').open`)
      assert.equal(await evaluate(`document.querySelector('[data-service-settings-row]').getBoundingClientRect().height < 90`), true, 'HTTP services use compact rows')
      assert.equal(await evaluate(`Array.from(document.querySelector('[aria-label="Service 1 check type"]').options).some(option => option.value.startsWith('regional:'))`), false, 'regional types are removed')
      for (let i = 0; i < 7; i++) await evaluate(`document.querySelector('button[aria-label^="Remove service "]').click()`)
      await waitFor(`!document.querySelector('button[aria-label^="Remove service "]')`)
      await evaluate(`${button('Add service')}.click()`)
      await waitFor(`document.querySelector('[aria-label="Service 1 name"]')`)
      await setInput('Service 1 name', 'My endpoint')
      await setInput('Service 1 URL', 'https://example.com/health')
      await setInput('Service 1 expected HTTP codes', '200/204')
      await evaluate(`${button('Add service')}.click()`)
      await waitFor(`document.querySelector('[aria-label="Service 2 check type"]')`)
      await evaluate(`(() => { const select = document.querySelector('[aria-label="Service 2 check type"]'); select.value = 'text'; select.dispatchEvent(new Event('change', { bubbles: true })); })()`)
      await waitFor(`document.querySelector('[aria-label="Service 2 available response"]')`)
      await setInput('Service 2 name', 'My text service')
      await setInput('Service 2 URL', 'https://example.com/text')
      await setInput('Service 2 available response', 'Welcome')
      await evaluate(`${button('Add service')}.click()`)
      await waitFor(`document.querySelector('[aria-label="Service 3 check type"]')`)
      await evaluate(`(() => { const select = document.querySelector('[aria-label="Service 3 check type"]'); select.value = 'json'; select.dispatchEvent(new Event('change', { bubbles: true })); })()`)
      await waitFor(`document.querySelector('[aria-label="Service 3 JSON path"]')`)
      await setInput('Service 3 name', 'My JSON service')
      await setInput('Service 3 URL', 'https://example.com/status')
      await setInput('Service 3 JSON path', 'data.allowed')
      await setInput('Service 3 available response', 'true')
      await setInput('Service 3 blocked response', 'false')
      await evaluate(`document.querySelector('button[type="submit"][form="settings-settings"]').click()`)
      await waitFor(`Array.from(document.querySelectorAll('[role="status"]')).some(el => el.textContent.includes('saved'))`)
      const saved = await evaluate(`window.api.settings.get().then(settings => settings.general.serviceCheckTargets)`)
      assert.equal(saved.length, 3)
      assert.equal(saved[0].url, 'https://example.com/health')
      assert.equal(saved[0].expected, '200/204')
      assert.equal(saved[1].content.source, 'text')
      assert.equal(saved[1].content.available, 'Welcome')
      assert.deepEqual(saved[2].content, { source: 'json', path: 'data.allowed', available: 'true', blocked: 'false' })
      await evaluate(`document.querySelector('[aria-label="Proxy groups"]').click()`)
      await waitFor(`document.querySelector('button[aria-label^="Check services via "]')`)
      const label = await evaluate(`document.querySelector('button[aria-label^="Check services via "]').getAttribute('aria-label')`)
      await evaluate(`document.querySelector('button[aria-label^="Check services via "]').click()`)
      await waitFor(`document.querySelector('[role="dialog"]')?.textContent.includes('My endpoint')`)
      await new Promise(resolve => setTimeout(resolve, 250))
      assert.equal(await evaluate(`document.activeElement === document.querySelector('[role="dialog"] h2')`), true, 'opening focuses the title instead of the help trigger')
      assert.equal(await evaluate(`!!document.querySelector('[role="tooltip"]')`), false, 'help does not open automatically')
      await evaluate(`(() => { const help = document.querySelector('[role="dialog"] button[aria-label="About service checks"]'); help.focus(); help.dispatchEvent(new FocusEvent('focusin', { bubbles: true })); })()`)
      await waitFor(`document.querySelector('[role="tooltip"]')`)
      await evaluate(`(() => { const help = document.querySelector('[role="dialog"] button[aria-label="About service checks"]'); help.dispatchEvent(new FocusEvent('focusout', { bubbles: true })); document.querySelector('[role="dialog"] h2').focus(); })()`)
      await waitFor(`!document.querySelector('[role="tooltip"]')`)
      assert.equal(await evaluate(`document.querySelector('[role="dialog"] p')?.textContent.includes('Requests go')`), false, 'help text is in a tooltip')
      assert.equal(await evaluate(`!!document.querySelector('[role="dialog"] button[aria-label="About service checks"]')`), true)
      assert.equal(await evaluate(`!!document.querySelector('[data-service-check-list] [data-radix-scroll-area-viewport] [data-service-check-row]')`), true, 'services use scrollable row cards')
      assert.equal(await evaluate(`!!document.querySelector('[role="dialog"] [role="img"]')`), true, 'host flag uses EmojiText')
      assert.equal(await evaluate(`document.querySelector('[role="dialog"]').textContent.includes('Cloudflare')`), false)
      await evaluate(`${button('Check services')}.click()`)
      await waitFor(`window.serviceTest.calls().length === 1`)
      assert.equal(await evaluate(`${button('Testing...')}.disabled`), true)
      await evaluate(`window.serviceTest.finish('available')`)
      await waitFor(`document.querySelector('[role="dialog"]').textContent.includes('HTTP available')`)
      assert.deepEqual(await evaluate(`window.serviceTest.calls()`), [label.replace('Check services via ', '')])
      assert.equal(await evaluate(`window.serviceTest.selections()`), 0, 'checking never selects the host')
      await evaluate(`${button('Check services')}.click()`)
      await waitFor(`window.serviceTest.calls().length === 2`)
      await evaluate(`window.serviceTest.finish('rejected')`)
      await waitFor(`document.querySelector('[role="dialog"]').textContent.includes('Unexpected HTTP status')`)
      await evaluate(`${button('Check services')}.click()`)
      await waitFor(`window.serviceTest.calls().length === 3`)
      await evaluate(`window.serviceTest.finish('error')`)
      await waitFor(`document.querySelector('[role="dialog"] [role="alert"]')`)
      win.webContents.invalidate()
      await new Promise(resolve => setTimeout(resolve, 200))
      fs.writeFileSync(path.join(output, 'dialog.png'), (await win.webContents.capturePage()).toPNG())
      await evaluate(`document.querySelector('[role="dialog"] button:has(.sr-only)').click()`)
      await evaluate(`document.querySelector('[aria-label="Settings"]').click()`)
      await waitFor(`${button('Restore default services')}`)
      await evaluate(`${button('Restore default services')}.closest('details').querySelector('summary').click()`)
      await evaluate(`${button('Restore default services')}.click()`)
      await evaluate(`document.querySelector('button[type="submit"][form="settings-settings"]').click()`)
      await waitFor(`Array.from(document.querySelectorAll('[role="status"]')).some(el => el.textContent.includes('saved'))`)
      await evaluate(`document.querySelector('[aria-label="Proxy groups"]').click()`)
      await waitFor(`document.querySelector('button[aria-label^="Check services via "]')`)
      await evaluate(`document.querySelector('button[aria-label^="Check services via "]').click()`)
      await waitFor(`document.querySelectorAll('[data-service-check-row]').length === 7`)
      assert.equal(await evaluate(`(() => { const viewport = document.querySelector('[data-service-check-list] [data-radix-scroll-area-viewport]'); return viewport.scrollHeight > viewport.clientHeight; })()`), true, 'long list scrolls inside dialog')
      assert.equal(await evaluate(`(() => { const rect = document.querySelector('[role="dialog"]').getBoundingClientRect(); return rect.top >= 0 && rect.bottom <= innerHeight; })()`), true)
      await evaluate(`${button('Check services')}.click()`)
      await waitFor(`window.serviceTest.calls().length === 4`)
      await evaluate(`window.serviceTest.finish('available')`)
      await waitFor(`document.querySelector('[role="dialog"]').textContent.includes('HTTP available')`)
      await new Promise(resolve => setTimeout(resolve, 250))
      fs.writeFileSync(path.join(output, 'dialog.png'), (await win.webContents.capturePage()).toPNG())
      await evaluate(`document.querySelector('[role="dialog"] button:has(.sr-only)').click()`)
      await evaluate(`window.api.kernel.stop()`)
      await waitFor(`!document.querySelector('button[aria-label^="Check services via "]').disabled`)
      assert.deepEqual(errors, [])
      console.log('PASS: collapsed compact settings, HTTP/text/JSON persistence, no regional types, tooltip, flags, scrollable cards, request states and offline behavior')
    } finally { win.destroy(); app.quit() }
  }).catch(error => { console.error(error); app.exit(1) })
}
